"""Display-only camera apertures from the mounted Rated Case templates.

The dark camera lip encloses the phone. Segment its bright interior, fill lens
holes, and leave a one-preview-pixel inset so the photographed lip stays intact.
These rows never enter the printable mask or exported artwork.
"""
from pathlib import Path
import json
import numpy as np
from PIL import Image
from scipy import ndimage
ROOT=Path(__file__).resolve().parent.parent
result={}
for file in sorted((ROOT/'assets/cases').glob('rated-*-clear.webp')):
    a=np.array(Image.open(file).convert('RGBA').resize((1250,1500),Image.Resampling.LANCZOS))[:700]
    bright=(a[:,:,:3].mean(axis=2)>130)&(a[:,:,3]>240)
    labels,n=ndimage.label(bright)
    sizes=np.bincount(labels.ravel());sizes[0]=0
    for k in np.unique(np.concatenate([labels[0],labels[-1],labels[:,0],labels[:,-1]])): sizes[k]=0
    k=int(sizes.argmax());assert sizes[k]>1000,file
    mask=ndimage.binary_erosion(ndimage.binary_fill_holes(labels==k),iterations=1)
    ys,xs=np.where(mask);left=int(xs.min()*2);rows=[]
    for y in range(int(ys.min()),int(ys.max())+1):
        edges=np.flatnonzero(np.diff(np.r_[False,mask[y],False]));row=[int(y*2),int((y+1)*2),*[int(x*2) for x in edges]]
        if rows and rows[-1][2:]==row[2:]:rows[-1][1]=row[1]
        else:rows.append(row)
    key=file.name[len('rated-'):-len('-clear.webp')]
    result[key]={'bounds':[left,int(ys.min()*2),int(np.where(mask)[1].max()*2+2),int(ys.max()*2+2)],'rows':rows}
    print(key,int(mask.sum()),result[key]['bounds'])
(ROOT/'assets/rated-camera-geometry.js').write_text('// Display only. Generated by tools/build_rated_camera_geometry.py; never a print mask.\nwindow.KPRatedCameraGeometry='+json.dumps(result,separators=(',',':'))+';\n')
