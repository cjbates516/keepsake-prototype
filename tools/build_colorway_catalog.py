#!/usr/bin/env python3
"""Build the design-colorway index from the active library; existing slot IDs stay stable."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
groups={
 'City maps':'maps','Hometown':'maps','Christmas':'holiday','Halloween':'spooky',
 'Zodiac':'celestial','Celestial':'celestial','For Him':'outdoors','Outdoors':'outdoors','Scenery':'outdoors',
 'Florals':'floral','Birth flowers':'floral','Coquette':'floral','Hearts':'floral',
 'Fruits':'bright','Bright Pop':'bright','Retro & Y2K':'bright','Cute & kids':'pastel',
 'Coastal':'coastal','Clear':'pastel','Gradients & pastels':'pastel',
 'Animal print':'earth','Animals':'earth','Cars':'bold','Sports':'bold'
}
file=ROOT/'assets/colorway-catalog.js'
previous={}
if file.exists():
 text=file.read_text();previous=json.loads(text.split('=',1)[1].strip().rstrip(';'))
data=json.loads((ROOT/'assets/designs/designs.json').read_text());catalog={}
for d in data:
 if d.get('hidden') or d.get('active') is False:continue
 name=d['file'];old=previous.get(name,{})
 catalog[name]={**old,'group':old.get('group',groups.get(d['category'],'bright')),'method':old.get('method','map' if d['category']=='City maps' else 'palette'),'hash':d.get('hash','')}
 if name=='modern-yosemite-national-park-logo-for-mug.jpg':catalog[name].update(method='yosemite',group='outdoors')
# Keep retired entries so an existing pick code retains its colorway mapping.
for name,value in previous.items():catalog.setdefault(name,value)
file.write_text('/* Generated by tools/build_colorway_catalog.py. Keep slot mappings stable. */\nwindow.KP_COLORWAY_CATALOG='+json.dumps(catalog,separators=(',',':'),sort_keys=True)+';\n')
print(f'{len(catalog)} registered designs; five stable colorway slots per design')
