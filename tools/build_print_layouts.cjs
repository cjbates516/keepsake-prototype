/* Derive preview proportions and exact mask bounds from customizer kit sources.
   Run after changing a kit: node tools/build_print_layouts.cjs [--check]. Requires Pillow. */
const fs=require('fs'),path=require('path'),vm=require('vm'),cp=require('child_process');
const root=path.resolve(__dirname,'..'),s=fs.readFileSync(path.join(root,'customizer.html'),'utf8'),scope={};
vm.runInNewContext(s.slice(s.indexOf('  var KITS ='),s.indexOf('  var printPath=null')),scope);
const raw=cp.spawnSync('python3',['-c',`import json,sys
from PIL import Image
from pathlib import Path
root=Path(sys.argv[1]);kits=json.load(sys.stdin);out={}
for name,k in kits.items():
 im=Image.open(root/'assets/masks'/k['view']);b=im.getchannel('A').point(lambda a:255 if a>=128 else 0).getbbox()
 t=k['tpl'];f=k['fit'];rx=(t['pxH']/t['h']/f['sy'])/(t['pxW']/t['w']/f['sx'])
 out[name]={'mask':k['view'],'rx':rx,'box':list(b),'bleedX':18/(t['pxW']/t['w']/f['sx']),'bleedY':18/(t['pxH']/t['h']/f['sy'])}
print(json.dumps(out,sort_keys=True,indent=2))`,root],{input:JSON.stringify(scope.KITS),encoding:'utf8'});
if(raw.status!==0)throw Error(raw.stderr);
const data=JSON.parse(raw.stdout),text='/* Generated by tools/build_print_layouts.cjs. Physical artwork ratio and native mask bounds. */\nwindow.KP_PRINT_LAYOUTS = '+JSON.stringify(data,null,2)+';\n',file=path.join(root,'assets/print-layouts.js');
if(process.argv.includes('--check')){if(fs.readFileSync(file,'utf8')!==text)throw Error('Print layouts need regeneration');console.log('PASS print layout metadata matches kit geometry and native masks');}else fs.writeFileSync(file,text);
